        foreach (self::TEXTES as $groupe => $cles) {
            foreach ($cles as $cle => [$fr, $nl, $en]) {
                Translation::updateOrCreate(
                    ['cle' => $groupe.'.'.$cle],
                    ['groupe' => $groupe, 'fr' => $fr, 'nl' => $nl, 'en' => $en],
                );
            }
        }
    }

